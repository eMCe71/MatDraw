// Generates the COUNTRIES table of dist/profile-data.js (plan §7.3): [code, Polish name, English name] for the 249 ISO 3166-1
// alpha-2 codes plus XK (Kosovo), names from Intl.DisplayNames of this Node build (full ICU). Run once by hand and commit the
// result; the names never come from the browser, so every visitor sees the same list. PHP keeps only the codes
// (backend/src/Profiles.php COUNTRIES); tests/community.test.mjs checks that both lists are identical.
//   node scripts/gen-countries.mjs           rewrites the block between the countries markers in dist/profile-data.js
//   node scripts/gen-countries.mjs --print   prints the block instead
import {readFileSync,writeFileSync} from 'node:fs';
const CODES=`AD AE AF AG AI AL AM AO AQ AR AS AT AU AW AX AZ BA BB BD BE BF BG BH BI BJ BL BM BN BO BQ BR BS BT BV BW BY BZ
CA CC CD CF CG CH CI CK CL CM CN CO CR CU CV CW CX CY CZ DE DJ DK DM DO DZ EC EE EG EH ER ES ET FI FJ FK FM FO FR
GA GB GD GE GF GG GH GI GL GM GN GP GQ GR GS GT GU GW GY HK HM HN HR HT HU ID IE IL IM IN IO IQ IR IS IT JE JM JO JP
KE KG KH KI KM KN KP KR KW KY KZ LA LB LC LI LK LR LS LT LU LV LY MA MC MD ME MF MG MH MK ML MM MN MO MP MQ MR MS MT MU MV MW MX MY MZ
NA NC NE NF NG NI NL NO NP NR NU NZ OM PA PE PF PG PH PK PL PM PN PR PS PT PW PY QA RE RO RS RU RW
SA SB SC SD SE SG SH SI SJ SK SL SM SN SO SR SS ST SV SX SY SZ TC TD TF TG TH TJ TK TL TM TN TO TR TT TV TW TZ
UA UG UM US UY UZ VA VC VE VG VI VN VU WF WS YE YT ZA ZM ZW`.split(/\s+/);
if(CODES.length!==249||new Set(CODES).size!==249)throw new Error('expected 249 distinct ISO codes, got '+CODES.length);
const codes=[...CODES,'XK'].sort();
const pl=new Intl.DisplayNames(['pl'],{type:'region',fallback:'none'}),en=new Intl.DisplayNames(['en'],{type:'region',fallback:'none'});
// Typographic apostrophes become plain ones (one character for search and sorting in both languages).
const name=(dn,code)=>{const n=dn.of(code);if(!n||n===code)throw new Error('no name for '+code);return n.replace(/[‘’]/g,"'");};
const rows=codes.map(c=>[c,name(pl,c),name(en,c)]);
const lines=[];let letter='';
for(const r of rows){const text=JSON.stringify(r).replace(/"((?:[^"\\]|\\.)*)"/g,(m,s)=>"'"+s.replace(/\\"/g,'"').replace(/'/g,"\\'")+"'");if(r[0][0]!==letter){letter=r[0][0];lines.push(' '+text);}else lines[lines.length-1]+=','+text;}
const block='// countries:begin (generated by scripts/gen-countries.mjs, Node '+process.versions.node+', ICU '+process.versions.icu+')\nexport const COUNTRIES=[\n'+lines.join(',\n')+'\n];\n// countries:end';
if(process.argv.includes('--print'))console.log(block);
else{
 const file=new URL('../dist/profile-data.js',import.meta.url);const src=readFileSync(file,'utf8');
 const re=/\/\/ countries:begin[^\n]*\n[\s\S]*?\/\/ countries:end/;if(!re.test(src))throw new Error('countries markers not found in dist/profile-data.js');
 writeFileSync(file,src.replace(re,()=>block));console.log('COUNTRIES: '+rows.length+' entries written');
}
